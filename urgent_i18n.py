def lang_key(tag):
    """'ml-IN' -> 'ml'; anything we have no wording for -> 'en'."""
    k = (tag or "en").split("-")[0].lower()
    return k if k in SUPPORTED else "en"


def _steps(kind, key):
    if key == "en":
        return rules.STEPS.get(kind, rules.STEPS["other"])["text"]
    items = STEPS[key].get(kind, STEPS[key]["other"])
    return "\n".join(f"{i}. {s}" for i, s in enumerate(items, 1))


def urgent_text(kind, lang_tag, rn, room, name):
    """Return (text in the staff member's language, English text). Both are the same when the language is English."""
    def build(key):
        return (f"{INTRO[key].format(rn=rn, room=room, name=name)}\n\n{WHILE[key]}\n{_steps(kind, key)}\n\n{LIFE[key]}")
    key = lang_key(lang_tag)
    return build(key), build("en")


def check_text(lang_tag, first):
    key = lang_key(lang_tag)
    return CHECK[key].format(first=first), CHECK["en"].format(first=first)


def confirm_text(lang_tag):
    return CONFIRM[lang_key(lang_tag)]


